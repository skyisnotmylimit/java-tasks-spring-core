package dao;

import model.Event;
import model.Ticket;
import model.User;
import model.impl.EventImpl;
import model.impl.TicketImpl;
import model.impl.UserImpl;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import storage.Storage;

import java.util.Calendar;
import java.util.Date;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class DaoTest {

    private Storage storage;
    private UserDao userDao;
    private EventDao eventDao;
    private TicketDao ticketDao;

    @BeforeEach
    void setUp() {
        storage = new Storage();
        userDao = new UserDao();
        userDao.setStorage(storage);
        eventDao = new EventDao();
        eventDao.setStorage(storage);
        ticketDao = new TicketDao();
        ticketDao.setStorage(storage);
    }

    @Test
    void saveAssignsAutoGeneratedIdsAndStoresUnderNamespace() {
        User first = userDao.save(new UserImpl(0, "John", "john@example.com"));
        User second = userDao.save(new UserImpl(0, "Jane", "jane@example.com"));

        assertEquals(1, first.getId());
        assertEquals(2, second.getId());
        assertEquals(first, storage.get("user", 1));
        assertEquals(second, userDao.getById(2));
    }

    @Test
    void entitiesOfDifferentTypesDoNotClashInCommonStorage() {
        userDao.save(new UserImpl(0, "John", "john@example.com"));
        eventDao.save(new EventImpl(0, "Concert", new Date()));
        ticketDao.save(new TicketImpl(0, 1, 1, Ticket.Category.BAR, 1));

        assertEquals(1, userDao.getAll().size());
        assertEquals(1, eventDao.getAll().size());
        assertEquals(1, ticketDao.getAll().size());
        assertEquals(3, storage.size());
    }

    @Test
    void updateReturnsNullForMissingEntity() {
        assertNull(userDao.update(new UserImpl(42, "Ghost", "ghost@example.com")));
    }

    @Test
    void updateReplacesExistingEntity() {
        User user = userDao.save(new UserImpl(0, "John", "john@example.com"));
        user.setName("John Updated");

        User updated = userDao.update(user);

        assertEquals("John Updated", updated.getName());
        assertEquals("John Updated", userDao.getById(user.getId()).getName());
    }

    @Test
    void deleteRemovesEntityAndReportsResult() {
        User user = userDao.save(new UserImpl(0, "John", "john@example.com"));

        assertTrue(userDao.delete(user.getId()));
        assertNull(userDao.getById(user.getId()));
        assertFalse(userDao.delete(user.getId()));
    }

    @Test
    void getByEmailMatchesStrictly() {
        userDao.save(new UserImpl(0, "John", "john@example.com"));

        assertEquals("John", userDao.getByEmail("john@example.com").getName());
        assertNull(userDao.getByEmail("john@example"));
    }

    @Test
    void getByNameUsesContainsMatchingAndPagination() {
        userDao.save(new UserImpl(0, "Anna Johnson", "a@example.com"));
        userDao.save(new UserImpl(0, "Bob Johnson", "b@example.com"));
        userDao.save(new UserImpl(0, "Charlie Brown", "c@example.com"));

        List<User> page1 = userDao.getByName("Johnson", 1, 1);
        List<User> page2 = userDao.getByName("Johnson", 1, 2);
        List<User> page3 = userDao.getByName("Johnson", 1, 3);

        assertEquals(1, page1.size());
        assertEquals("Anna Johnson", page1.get(0).getName());
        assertEquals("Bob Johnson", page2.get(0).getName());
        assertTrue(page3.isEmpty());
        assertTrue(userDao.getByName("Nobody", 10, 1).isEmpty());
    }

    @Test
    void invalidPaginationParamsAreRejected() {
        assertThrows(IllegalArgumentException.class, () -> userDao.getByName("x", 0, 1));
        assertThrows(IllegalArgumentException.class, () -> userDao.getByName("x", 5, 0));
    }

    @Test
    void getEventsByTitleUsesContainsMatching() {
        eventDao.save(new EventImpl(0, "Spring Concert", new Date()));
        eventDao.save(new EventImpl(0, "Autumn Concert", new Date()));
        eventDao.save(new EventImpl(0, "Movie Night", new Date()));

        assertEquals(2, eventDao.getByTitle("Concert", 10, 1).size());
        assertTrue(eventDao.getByTitle("Opera", 10, 1).isEmpty());
    }

    @Test
    void getEventsForDayMatchesDayIgnoringTime() {
        Calendar calendar = Calendar.getInstance();
        calendar.set(2026, Calendar.MAY, 1, 19, 0, 0);
        Date eveningShow = calendar.getTime();
        calendar.set(2026, Calendar.MAY, 1, 10, 0, 0);
        Date morningShow = calendar.getTime();
        calendar.set(2026, Calendar.MAY, 2, 19, 0, 0);
        Date otherDayShow = calendar.getTime();

        eventDao.save(new EventImpl(0, "Evening", eveningShow));
        eventDao.save(new EventImpl(0, "Morning", morningShow));
        eventDao.save(new EventImpl(0, "Other", otherDayShow));

        calendar.set(2026, Calendar.MAY, 1, 0, 0, 0);
        List<Event> events = eventDao.getForDay(calendar.getTime(), 10, 1);

        assertEquals(2, events.size());
    }

    @Test
    void ticketLookupsByUserAndEvent() {
        ticketDao.save(new TicketImpl(0, 1, 1, Ticket.Category.STANDARD, 1));
        ticketDao.save(new TicketImpl(0, 1, 2, Ticket.Category.PREMIUM, 2));
        ticketDao.save(new TicketImpl(0, 2, 1, Ticket.Category.BAR, 1));

        assertEquals(2, ticketDao.getByUserId(1).size());
        assertEquals(2, ticketDao.getByEventId(1).size());
        assertTrue(ticketDao.isPlaceBooked(1, 2));
        assertFalse(ticketDao.isPlaceBooked(1, 3));
    }
}
