-- ============================================================
-- Database schema creation DDL for the Event Tickets Booking
-- application. Target DBMS: H2 (compatible with PostgreSQL).
-- ============================================================

DROP TABLE IF EXISTS user_accounts;
DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    email  VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(255)   NOT NULL,
    event_date    TIMESTAMP      NOT NULL,
    ticket_price  DECIMAL(19, 2) DEFAULT 0 NOT NULL
);

CREATE TABLE tickets (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  BIGINT      NOT NULL,
    user_id   BIGINT      NOT NULL,
    category  VARCHAR(20) NOT NULL,
    place     INT         NOT NULL,
    CONSTRAINT uk_tickets_event_place UNIQUE (event_id, place),
    CONSTRAINT fk_tickets_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_tickets_user  FOREIGN KEY (user_id)  REFERENCES users (id)  ON DELETE CASCADE
);

CREATE TABLE user_accounts (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT         NOT NULL,
    amount   DECIMAL(19, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT uk_user_accounts_user UNIQUE (user_id),
    CONSTRAINT fk_user_accounts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
